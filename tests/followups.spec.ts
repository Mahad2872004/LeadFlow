import {test,expect} from '@playwright/test'
import {isCalendarDate,isTaskDue,localDate,taskState} from '../src/lib/dates'
import {createTask,toggleTask} from '../src/lib/model'
import {sampleData} from '../src/lib/seed'
import {isData} from '../src/lib/storage'

test('calendar validation rejects rollover dates and handles leap years',()=>{
 for(const date of ['2026-02-30','2026-02-29','1900-02-29','2026-04-31','2026-13-01','2026-00-01','2026-01-00','0000-01-01','2026-1-1','invalid']) expect(isCalendarDate(date),date).toBe(false)
 for(const date of ['2024-02-29','2000-02-29','2026-12-31','0001-01-01','9999-12-31']) expect(isCalendarDate(date),date).toBe(true)
 expect(localDate(new Date(2026,0,1,0,5))).toBe('2026-01-01')
 expect(taskState({due:'2025-12-31',completed:false},'2026-01-01')).toBe('Overdue')
 expect(taskState({due:'2026-01-01',completed:false},'2026-01-01')).toBe('Due today')
 expect(taskState({due:'2026-01-02',completed:false},'2026-01-01')).toBe('Upcoming')
 expect(taskState({due:'2025-12-31',completed:true},'2026-01-01')).toBe('Completed')
 expect(isTaskDue({due:'2025-12-31',completed:true},'2026-01-01')).toBe(false)
})
test('task validation, persistence schema and completion history',()=>{
 const data=sampleData()
 expect(()=>createTask(data,'sample-0','2026-02-30','Call')).toThrow()
 expect(()=>createTask(data,'missing','2026-02-28','Call')).toThrow()
 expect(()=>createTask(data,'sample-0','2026-02-28','  ')).toThrow()
 expect(()=>createTask(data,'sample-0','2026-02-28','x'.repeat(2001))).toThrow()
 const next=createTask(data,'sample-0','2024-02-29','  Call tomorrow  ')
 expect(next.tasks[0].notes).toBe('Call tomorrow')
 expect(next.activities[0].text).toContain('Follow-up scheduled for 2024-02-29')
 const completed=toggleTask(next,next.tasks[0].id)
 expect(completed.tasks[0].completed).toBe(true)
 expect(completed.activities[0].text).toBe('Follow-up completed: Call tomorrow')
 const reopened=toggleTask(completed,next.tasks[0].id)
 expect(reopened.tasks[0].completed).toBe(false)
 expect(reopened.activities[0].text).toBe('Follow-up reopened: Call tomorrow')
 expect(isData(reopened)).toBe(true)
 expect(isData({...next,tasks:[{...next.tasks[0],due:'2026-02-30'}]})).toBe(false)
 expect(data.tasks).toHaveLength(3)
})

test.describe('local follow-up lifecycle',()=>{
 test.use({timezoneId:'Asia/Karachi'})
 test('due states, completion, reopening, persistence, timeline and midnight refresh',async({page})=>{
  await page.clock.install({time:new Date('2026-10-18T18:59:50Z')})
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'Pipeline snapshot'})).toBeVisible()
  await page.evaluate(()=>{const data=JSON.parse(localStorage.getItem('leadflow.demo.v1')!);data.tasks=[];localStorage.setItem('leadflow.demo.v1',JSON.stringify(data))})
  await page.reload()
  await expect(page.getByRole('button',{name:'Follow-ups due: 0. View follow-ups due',exact:true})).toBeVisible()
  await page.getByRole('navigation').getByRole('button',{name:'Follow-ups',exact:false}).click()
  for(const [date,notes] of [['2026-10-17','Past call'],['2026-10-18','Today call'],['2026-10-19','Future call']]){
   await page.getByRole('button',{name:'Add follow-up',exact:false}).click()
   await page.getByLabel('Due date *').fill(date)
   await page.getByLabel('Notes *').fill('  ')
   await page.getByRole('button',{name:'Schedule follow-up'}).click()
   await expect(page.getByRole('alert')).toContainText('valid due date')
   await page.getByLabel('Notes *').fill(notes)
   await page.getByRole('button',{name:'Schedule follow-up'}).click()
  }
  await expect(page.locator('.task-state.overdue')).toHaveCount(1)
  await expect(page.locator('.task-state.due-today')).toHaveCount(1)
  await expect(page.locator('.task-state.upcoming')).toHaveCount(1)
  await page.getByLabel('Filter tasks').selectOption('Overdue')
  await expect(page.getByRole('checkbox')).toHaveCount(1)
  await page.getByLabel('Complete Past call').click()
  await expect(page.getByRole('checkbox')).toHaveCount(0)
  await page.getByLabel('Filter tasks').selectOption('Completed')
  await expect(page.getByLabel('Reopen Past call')).toBeChecked()
  await expect(page.locator('.task-state.completed')).toHaveCount(1)
  await page.reload()
  await expect(page.getByRole('button',{name:'Follow-ups due: 1. View follow-ups due',exact:true})).toBeVisible()
  await page.getByRole('navigation').getByRole('button',{name:'Follow-ups',exact:false}).click()
  await page.getByLabel('Filter tasks').selectOption('Completed')
  await page.getByLabel('Reopen Past call').click()
  await page.getByRole('navigation').getByRole('button',{name:'Activity',exact:true}).click()
  await expect(page.getByRole('list',{name:'Activity timeline'})).toContainText('Follow-up reopened: Past call')
  await expect(page.getByRole('list',{name:'Activity timeline'})).toContainText('Follow-up completed: Past call')
  await expect(page.getByRole('list',{name:'Activity timeline'})).toContainText('Follow-up scheduled for 2026-10-19: Future call')
  await page.getByRole('navigation').getByRole('button',{name:'Overview'}).click()
  await expect(page.getByRole('button',{name:'Follow-ups due: 2. View follow-ups due',exact:true})).toBeVisible()
  await page.clock.fastForward(15_000)
  await expect(page.getByRole('button',{name:'Follow-ups due: 3. View follow-ups due',exact:true})).toBeVisible()
  await expect(page.locator('.task-state.overdue')).toHaveCount(2)
  await expect(page.locator('.task-state.due-today')).toHaveCount(1)
 })
})
