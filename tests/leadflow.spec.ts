for(const width of [360,768,1440]) {
 test(`dashboard navigation and controls fit at ${width}px`,async({page})=>{
  await page.setViewportSize({width,height:900})
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'Recent leads',exact:false})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  const status=page.getByLabel('Status for Olivia Bennett')
  await status.scrollIntoViewIfNeeded()
  const box=await status.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x+box!.width).toBeLessThanOrEqual(width)
  await status.selectOption('Qualified')
  await expect(status).toHaveValue('Qualified')
  await page.getByLabel('View Olivia Bennett').click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('navigation').getByRole('button',{name:'Leads',exact:true}).click()
  await expect(page.getByRole('heading',{name:'All leads',exact:false})).toBeVisible()
  await page.getByRole('navigation').getByRole('button',{name:'Overview'}).click()
  await page.screenshot({path:`test-results/dashboard-${width}.png`,fullPage:true})
 })
}


