test('corrupt storage is preserved until an explicit reset',async({page})=>{
 await page.goto('/')
 await page.evaluate(()=>localStorage.setItem('leadflow.demo.v1','broken'))
 await page.reload()
 await expect(page.getByRole('alert')).toContainText('has not been overwritten')
 expect(await page.evaluate(()=>localStorage.getItem('leadflow.demo.v1'))).toBe('broken')
 await page.getByRole('button',{name:'Reset demo data',exact:false}).click()
 await page.getByRole('dialog').getByRole('button',{name:'Reset demo data',exact:true}).click()
 await expect(page.getByRole('alert')).toHaveCount(0)
 await expect(page.getByRole('table').getByRole('row')).toHaveCount(6)
})
